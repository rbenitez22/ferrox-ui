//! Areas → Rust source: one `LazyLock<HelpTopic>` static per topic, built
//! with ferrox-ui's `HelpTopic` builder, and `TOPICS`, the `HelpTopics`
//! registry of them all. Nothing is parsed at runtime.

use std::fmt::Write;

use crate::model::{Area, Block, Topic};

/// How generated code names things.
pub struct RustOptions<'a> {
    /// The path generated code uses for ferrox-ui (`::ferrox_ui`).
    pub crate_path: &'a str,
    /// Prepended to each id for `.guide(..)` (`/help#`); none, no guide link.
    pub guide_prefix: Option<&'a str>,
    /// Shown in the generated header, so a reader knows where to edit.
    pub source: &'a str,
}

/// The static's name for a topic id: `recipe-search` → `RECIPE_SEARCH`.
pub fn static_name(id: &str) -> String {
    id.replace('-', "_").to_ascii_uppercase()
}

/// The whole generated file.
pub fn render_rust(areas: &[Area], options: &RustOptions) -> String {
    let mut out = String::new();
    writeln!(out, "// @generated by ferrox-help-build from {}. Edit the Markdown, not this file.", options.source).unwrap();
    for area in areas {
        writeln!(out, "\n// {} ({})", area.title, area.file).unwrap();
        for topic in &area.topics {
            render_topic(&mut out, topic, options);
        }
    }
    render_registry(&mut out, areas, options.crate_path);
    out
}

/// `TOPICS`: every area and its topics, in reading order.
fn render_registry(out: &mut String, areas: &[Area], krate: &str) {
    writeln!(out, "\n/// Every topic, in reading order: for `provide_help_topics` and `HelpGuide`.").unwrap();
    writeln!(out, "pub static TOPICS: ::std::sync::LazyLock<{krate}::HelpTopics> = ::std::sync::LazyLock::new(|| {{").unwrap();
    writeln!(out, "    {krate}::HelpTopics::new([").unwrap();
    for area in areas {
        let topics: Vec<String> = area.topics.iter().map(|t| format!("{}.clone()", static_name(&t.id))).collect();
        write!(out, "        {krate}::HelpArea::new({:?}, [{}])", area.title, topics.join(", ")).unwrap();
        if let Some(intro) = &area.intro {
            write!(out, ".intro({intro:?})").unwrap();
        }
        writeln!(out, ",").unwrap();
    }
    writeln!(out, "    ])").unwrap();
    writeln!(out, "}});").unwrap();
}

fn render_topic(out: &mut String, topic: &Topic, options: &RustOptions) {
    let krate = options.crate_path;
    writeln!(out, "\n/// {}", topic.title).unwrap();
    writeln!(
        out,
        "pub static {}: ::std::sync::LazyLock<{krate}::HelpTopic> = ::std::sync::LazyLock::new(|| {{",
        static_name(&topic.id)
    )
    .unwrap();
    writeln!(out, "    {krate}::HelpTopic::new({:?}, {:?})", topic.id, topic.title).unwrap();
    for block in &topic.blocks {
        writeln!(out, "        {}", render_block(block)).unwrap();
    }
    if !topic.related.is_empty() {
        let ids: Vec<&str> = topic.related.iter().map(|r| r.id.as_str()).collect();
        writeln!(out, "        .related({})", string_array(&ids)).unwrap();
    }
    if let Some(prefix) = options.guide_prefix {
        writeln!(out, "        .guide({:?})", format!("{prefix}{}", topic.id)).unwrap();
    }
    writeln!(out, "}});").unwrap();
}

fn render_block(block: &Block) -> String {
    match block {
        Block::Paragraph(text) => format!(".paragraph({text:?})"),
        Block::List(items) => format!(".list({})", string_array(items)),
        Block::Table { columns, rows } => {
            let rows: Vec<String> = rows.iter().map(|row| string_array(row)).collect();
            format!(".table({}, [{}])", string_array(columns), rows.join(", "))
        }
    }
}

/// `["a", "b"]`, each element an escaped string literal.
fn string_array<S: AsRef<str>>(items: &[S]) -> String {
    let literals: Vec<String> = items.iter().map(|s| format!("{:?}", s.as_ref())).collect();
    format!("[{}]", literals.join(", "))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::parse_area;

    #[test]
    fn names() {
        assert_eq!(static_name("recipe-search"), "RECIPE_SEARCH");
        assert_eq!(static_name("a2-b"), "A2_B");
    }

    #[test]
    fn renders_a_topic() {
        let area = parse_area("a.md", "# A\n## Say \"hi\" {#say-hi}\nOne ½.\n\n- x\n\n| K | V |\n|---|---|\n| 1 | 2 |\n\nRelated: #other\n").unwrap();
        let code = render_rust(&[area], &RustOptions { crate_path: "::ferrox_ui", guide_prefix: Some("/help#"), source: "docs/help" });
        let expected = r#"// @generated by ferrox-help-build from docs/help. Edit the Markdown, not this file.

// A (a.md)

/// Say "hi"
pub static SAY_HI: ::std::sync::LazyLock<::ferrox_ui::HelpTopic> = ::std::sync::LazyLock::new(|| {
    ::ferrox_ui::HelpTopic::new("say-hi", "Say \"hi\"")
        .paragraph("One ½.")
        .list(["x"])
        .table(["K", "V"], [["1", "2"]])
        .related(["other"])
        .guide("/help#say-hi")
});

/// Every topic, in reading order: for `provide_help_topics` and `HelpGuide`.
pub static TOPICS: ::std::sync::LazyLock<::ferrox_ui::HelpTopics> = ::std::sync::LazyLock::new(|| {
    ::ferrox_ui::HelpTopics::new([
        ::ferrox_ui::HelpArea::new("A", [SAY_HI.clone()]),
    ])
});
"#;
        assert_eq!(code, expected);
    }
}
