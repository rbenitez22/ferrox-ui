//! Writing the CSS file and fonts an app links from `index.html`.

use std::fs;
use std::path::Path;

use crate::builtin::{FONTS_CSS, FONT_FILES, LOADING_CSS, THEMES, TOKENS_CSS};
use crate::embed::{discover, ThemeSource};
use crate::VERSION;

/// The generated stylesheet's file name inside the output directory.
pub const CSS_FILE: &str = "ferrox.css";

/// The fonts folder's name inside the output directory.
pub const FONTS_DIR: &str = "fonts";

/// Writes `ferrox.css` (fonts, tokens, every theme, the loading screen) and
/// `fonts/` into `out_dir`, relative to the crate root. `themes_dir`, if given,
/// holds the app's own theme files; one with a built-in's id replaces it.
///
/// Files are only rewritten when their content changes, so a watching
/// `trunk serve` is not sent into a rebuild loop. Panics, failing the build, on
/// an invalid theme file or an I/O error.
pub fn write_css(out_dir: &str, themes_dir: Option<&str>) {
    let root = Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"))
        .to_path_buf();
    let app_themes = match themes_dir {
        Some(dir) => {
            let dir = root.join(dir);
            println!("cargo:rerun-if-changed={}", dir.display());
            discover(&dir).unwrap_or_else(|errors| {
                let lines: Vec<String> = errors.iter().map(|e| format!("  - {e}")).collect();
                panic!("invalid theme files in {}:\n{}", dir.display(), lines.join("\n"));
            })
        }
        None => Vec::new(),
    };
    let out = root.join(out_dir);
    write_assets(&out, &app_themes)
        .unwrap_or_else(|e| panic!("cannot write ferrox-theme assets into {out_dir}: {e}"));
    // Watch the output too: if it is deleted (a clean checkout, `git clean`),
    // the next cargo run re-runs this script and writes it again.
    println!("cargo:rerun-if-changed={}", out.join(CSS_FILE).display());
    println!("cargo:rerun-if-changed={}", out.join(FONTS_DIR).display());
}

/// The whole stylesheet. Order matters: tokens before themes, so
/// `:root[data-theme]` also wins on source order.
pub(crate) fn stylesheet(app_themes: &[ThemeSource]) -> String {
    let mut css = format!("/* @generated by ferrox-theme-build {VERSION}. Do not edit. */\n\n");
    css.push_str(FONTS_CSS);
    css.push('\n');
    css.push_str(TOKENS_CSS);
    for (file, theme_css) in THEMES {
        let id = file.trim_end_matches(".css");
        if !app_themes.iter().any(|t| t.meta.id == id) {
            css.push('\n');
            css.push_str(theme_css);
        }
    }
    for theme in app_themes {
        css.push('\n');
        css.push_str(&theme.css);
    }
    css.push('\n');
    css.push_str(LOADING_CSS);
    css
}

pub(crate) fn write_assets(out: &Path, app_themes: &[ThemeSource]) -> std::io::Result<()> {
    let fonts = out.join(FONTS_DIR);
    fs::create_dir_all(&fonts)?;
    write_if_changed(&out.join(CSS_FILE), stylesheet(app_themes).as_bytes())?;
    for (name, bytes) in FONT_FILES {
        write_if_changed(&fonts.join(name), bytes)?;
    }
    Ok(())
}

fn write_if_changed(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    if fs::read(path).is_ok_and(|existing| existing == bytes) {
        return Ok(());
    }
    fs::write(path, bytes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::contract::{parse_theme, tests::full_theme};

    fn app_theme(id: &str) -> ThemeSource {
        let css = full_theme(id);
        ThemeSource { meta: parse_theme(&format!("{id}.css"), &css).unwrap(), css }
    }

    #[test]
    fn stylesheet_has_fonts_tokens_every_theme_and_loading_in_order() {
        let css = stylesheet(&[app_theme("harbor")]);
        let at = |needle: &str| css.find(needle).unwrap_or_else(|| panic!("missing {needle}"));
        assert!(at("@font-face") < at(":root {"));
        assert!(at(":root {") < at(":root[data-theme='jamaica-dark']"));
        assert!(at(":root[data-theme='jamaica-dark']") < at(":root[data-theme='harbor']"));
        assert!(at(":root[data-theme='harbor']") < at(".ferrox-loading {"));
    }

    #[test]
    fn an_app_theme_replaces_the_builtin_with_its_id() {
        let mut replacement = app_theme("foundry");
        replacement.css = replacement.css.replace("#000", "#123456");
        let css = stylesheet(&[replacement]);
        assert_eq!(css.matches(":root[data-theme='foundry']").count(), 1);
        assert!(css.contains("#123456"));
    }

    #[test]
    fn writes_css_and_fonts_and_leaves_unchanged_files_alone() {
        let out = std::env::temp_dir().join(format!("ferrox-assets-{}", std::process::id()));
        write_assets(&out, &[]).unwrap();
        let css_path = out.join(CSS_FILE);
        assert!(fs::read_to_string(&css_path).unwrap().contains(".ferrox-loading"));
        for (name, bytes) in FONT_FILES {
            assert_eq!(&fs::read(out.join(FONTS_DIR).join(name)).unwrap(), bytes);
        }
        let written = fs::metadata(&css_path).unwrap().modified().unwrap();
        std::thread::sleep(std::time::Duration::from_millis(20));
        write_assets(&out, &[]).unwrap();
        assert_eq!(fs::metadata(&css_path).unwrap().modified().unwrap(), written);
        fs::remove_dir_all(&out).unwrap();
    }
}
