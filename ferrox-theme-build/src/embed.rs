//! Discovering theme files and generating the Rust code that registers them.

use std::fs;
use std::path::{Path, PathBuf};

use crate::builtin::THEMES;
use crate::contract::{parse_theme, ThemeError, ThemeMeta};
use crate::VERSION;

/// Name of the file [`embed_themes`] writes into `OUT_DIR`.
pub const OUTPUT_FILE: &str = "ferrox_themes.rs";

/// Name of the file [`embed_builtin_themes`] writes into `OUT_DIR` (ferrox-theme's own).
const BUILTIN_OUTPUT_FILE: &str = "ferrox_builtin_themes.rs";

/// A theme file that passed the contract: its metadata and its CSS.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub struct ThemeSource {
    pub meta: ThemeMeta,
    pub css: String,
}

/// The `*.css` files directly inside `dir`.
fn css_files(dir: &Path) -> Result<Vec<PathBuf>, ThemeError> {
    let io_err = |e: std::io::Error| ThemeError::Io { path: dir.display().to_string(), message: e.to_string() };
    let files: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(io_err)?
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "css"))
        .collect();
    Ok(files)
}

fn read_theme(path: &Path) -> Result<ThemeSource, ThemeError> {
    let css = fs::read_to_string(path).map_err(|e| ThemeError::Io { path: path.display().to_string(), message: e.to_string() })?;
    let file = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
    let meta = parse_theme(file, &css)?;
    Ok(ThemeSource { meta, css })
}

/// Parses every theme in `dir`, sorted by id. Returns all errors, not just the first.
pub fn discover(dir: &Path) -> Result<Vec<ThemeSource>, Vec<ThemeError>> {
    let files = css_files(dir).map_err(|e| vec![e])?;
    let (themes, errors): (Vec<_>, Vec<_>) = files.iter().map(|path| read_theme(path)).partition(Result::is_ok);
    if errors.is_empty() {
        let mut themes: Vec<ThemeSource> = themes.into_iter().map(Result::unwrap).collect();
        themes.sort_by(|a, b| a.meta.id.cmp(&b.meta.id));
        Ok(themes)
    } else {
        Err(errors.into_iter().map(Result::unwrap_err).collect())
    }
}

/// Renders the block expression that `include!` splices in: a version check,
/// then a `&'static [ThemeFile]`. `root` is how the generated code names the
/// ferrox-theme crate (`::ferrox_theme`, a re-export such as
/// `::webapp_lib::theme`, or `crate` inside ferrox-theme).
pub fn render(themes: &[ThemeMeta], root: &str) -> String {
    let mut out = format!(
        "// @generated by ferrox-theme-build {VERSION}. Do not edit.\n{{\n    const _: () = {root}::check_build_version({VERSION:?});\n    const THEMES: &[{root}::ThemeFile] = &[\n"
    );
    for theme in themes {
        out.push_str(&format!(
            "        {root}::ThemeFile::new({:?}, {:?}, {}, {:?}),\n",
            theme.id, theme.family, theme.dark, theme.label,
        ));
    }
    out.push_str("    ];\n    THEMES\n}\n");
    out
}

fn env_dir(name: &str) -> PathBuf {
    PathBuf::from(std::env::var(name).unwrap_or_else(|_| panic!("{name} is set by cargo for build scripts")))
}

/// Fails the build with every problem found.
fn report(dir: &Path, errors: &[ThemeError]) -> ! {
    let lines: Vec<String> = errors.iter().map(|e| format!("  - {e}")).collect();
    panic!("invalid theme files in {}:\n{}", dir.display(), lines.join("\n"));
}

fn write_generated(file: &str, code: &str) {
    let target = env_dir("OUT_DIR").join(file);
    fs::write(&target, code).unwrap_or_else(|e| panic!("cannot write {}: {e}", target.display()));
}

/// Like [`embed_themes`], for an app that reaches ferrox-theme through a
/// re-export: `embed_themes_for("style/themes", "::webapp_lib::theme")`.
pub fn embed_themes_for(dir: &str, root: &str) {
    let theme_dir = env_dir("CARGO_MANIFEST_DIR").join(dir);
    // A directory path makes cargo rescan it, so an added file triggers a rebuild.
    println!("cargo:rerun-if-changed={}", theme_dir.display());
    let themes = discover(&theme_dir).unwrap_or_else(|errors| report(&theme_dir, &errors));
    let metas: Vec<ThemeMeta> = themes.into_iter().map(|t| t.meta).collect();
    write_generated(OUTPUT_FILE, &render(&metas, root));
}

/// Validates the app's theme files in `dir` (relative to the crate root) and
/// writes `$OUT_DIR/ferrox_themes.rs` for `ferrox_theme::register`. Panics,
/// failing the build, with every problem found.
pub fn embed_themes(dir: &str) {
    embed_themes_for(dir, "::ferrox_theme");
}

/// ferrox-theme's own build script: registers the built-in themes.
#[doc(hidden)]
pub fn embed_builtin_themes() {
    let metas: Vec<ThemeMeta> = THEMES
        .iter()
        .map(|(file, css)| parse_theme(file, css).unwrap_or_else(|e| panic!("built-in theme: {e}")))
        .collect();
    write_generated(BUILTIN_OUTPUT_FILE, &render(&metas, "crate"));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_output() {
        let meta = parse_theme("sea.css", &crate::contract::tests::full_theme("sea")).unwrap();
        let expected = format!(
            "// @generated by ferrox-theme-build {VERSION}. Do not edit.\n{{\n    const _: () = ::ferrox_theme::check_build_version({VERSION:?});\n    const THEMES: &[::ferrox_theme::ThemeFile] = &[\n        ::ferrox_theme::ThemeFile::new(\"sea\", \"sea\", false, \"Sea\"),\n    ];\n    THEMES\n}}\n"
        );
        assert_eq!(render(&[meta], "::ferrox_theme"), expected);
    }

    #[test]
    fn discover_reports_every_bad_file() {
        let dir = std::env::temp_dir().join(format!("ferrox-discover-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        fs::write(dir.join("good.css"), crate::contract::tests::full_theme("good")).unwrap();
        fs::write(dir.join("Bad.css"), "").unwrap();
        fs::write(dir.join("empty.css"), "/* */").unwrap();
        let errors = discover(&dir).unwrap_err();
        fs::remove_dir_all(&dir).unwrap();
        assert_eq!(errors.len(), 2, "{errors:?}");
    }
}
